    private async Task ReloadProductsAsync(DaftarContext ctx)
    {
        var keep = _selectedProductId;

        // Query stock on hand per product
        var onHandByProduct = await ctx.StockBalances
            .Where(b => b.Lot != null)
            .GroupBy(b => b.Lot!.ProductId)
            .Select(g => new { ProductId = g.Key, TotalOnHand = g.Sum(b => b.Quantity) })
            .ToDictionaryAsync(x => x.ProductId, x => x.TotalOnHand);

        // Query base units per product
        var baseUnitsByProduct = await ctx.ProductUnits
            .Where(u => u.IsBase)
            .ToDictionaryAsync(u => u.ProductId, u => u.Name);

        // Query unit counts per product
        var unitCountsByProduct = await ctx.ProductUnits
            .GroupBy(u => u.ProductId)
            .Select(g => new { ProductId = g.Key, Count = g.Count() })
            .ToDictionaryAsync(x => x.ProductId, x => x.Count);

        // Query barcodes
        var barcodeList = await ctx.ProductUnits
            .Where(u => !string.IsNullOrEmpty(u.Barcode))
            .Select(u => new { u.ProductId, u.Barcode })
            .ToListAsync();

        _barcodeToProductId.Clear();
        foreach (var b in barcodeList)
        {
            if (!string.IsNullOrWhiteSpace(b.Barcode))
                _barcodeToProductId[b.Barcode.Trim()] = b.ProductId;
        }

        var list = await ctx.Products
            .OrderBy(p => p.Name)
            .ToListAsync();

        Products.Clear();
        foreach (var product in list)
        {
            onHandByProduct.TryGetValue(product.Id, out var onHand);
            baseUnitsByProduct.TryGetValue(product.Id, out var baseUnitName);
            unitCountsByProduct.TryGetValue(product.Id, out var unitCount);

            Products.Add(new ProductRow(
                Id: product.Id,
                Sku: product.Sku,
                Name: product.Name,
                IsActive: product.IsActive,
                ReorderLevel: product.ReorderLevel,
                TotalOnHand: onHand,
                BaseUnitName: baseUnitName ?? "",
                UnitsCount: unitCount > 0 ? unitCount : 1));
        }

        TotalProductsCount = Products.Count;
        ActiveProductsCount = Products.Count(p => p.IsActive);
        LowStockProductsCount = Products.Count(p => p.IsLowStock);
        TotalUnitsCount = unitCountsByProduct.Values.Sum();

        ApplyFilter();

        _selectedProductId = Products.Any(p => p.Id == keep) ? keep : 0;
        SelectedProduct = Products.FirstOrDefault(p => p.Id == _selectedProductId);
    }

    private void ApplyFilter()
    {
        var query = Products.AsEnumerable();

        if (FilterIndex == 1) // نشط
            query = query.Where(p => p.IsActive);
        else if (FilterIndex == 2) // نقص مخزون
            query = query.Where(p => p.IsLowStock);
        else if (FilterIndex == 3) // معطل
            query = query.Where(p => !p.IsActive);

        if (!string.IsNullOrWhiteSpace(SearchText))
        {
            var term = SearchText.Trim();
            // Check if term matches barcode
            var barcodeMatches = _barcodeToProductId
                .Where(kvp => kvp.Key.Contains(term, StringComparison.OrdinalIgnoreCase))
                .Select(kvp => kvp.Value)
                .ToHashSet();

            query = query.Where(p =>
                p.Name.Contains(term, StringComparison.OrdinalIgnoreCase) ||
                p.Sku.Contains(term, StringComparison.OrdinalIgnoreCase) ||
                barcodeMatches.Contains(p.Id));
        }

        FilteredProducts.Clear();
        foreach (var p in query)
            FilteredProducts.Add(p);
    }

