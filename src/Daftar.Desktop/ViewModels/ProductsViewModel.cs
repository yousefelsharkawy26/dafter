            }

            var sku = Product.NormalizeSku(EditSku);
            if (sku != product.Sku && await ctx.Products.AnyAsync(p => p.Sku == sku && p.Id != _selectedProductId))
            {
                HasError = true;
                Status = $"الكود {sku} مستخدم بالفعل لصنف آخر";
                return;
            }

            product.Sku = sku;
            product.Name = EditName.Trim();
            product.ReorderLevel = decimal.TryParse(EditReorderLevel, out var reorder) ? reorder : null;
            product.IsActive = EditIsActive;

            await ctx.SaveChangesAsync();

            HasError = false;
            Status = $"تم حفظ تعديلات الصنف '{product.Name}' بنجاح";

            await ReloadProductsAsync(ctx);
        }
        catch (Exception ex)
        {
            HasError = true;
            Status = $"خطأ: {ex.Message}";
        }
    }

    public static string GenerateSkuFromName(string? name)
    {
        if (string.IsNullOrWhiteSpace(name))
            return string.Empty;

        var tokens = name.Trim()
            .Split([' ', '\t', '-', '_', '/', '\\', '،', ','], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);

        if (tokens.Length == 0)
            return string.Empty;

        var firstWord = tokens[0];

        // Search for the first number in the remaining tokens or in the entire name
        string? numberPart = null;
        for (int i = 1; i < tokens.Length; i++)
        {
            var match = System.Text.RegularExpressions.Regex.Match(tokens[i], @"\d+(\.\d+)?");
            if (match.Success)
            {
                numberPart = match.Value;
                break;
            }
        }

        if (!string.IsNullOrEmpty(numberPart))
        {
            return $"{firstWord}-{numberPart}";
        }

        // If first word itself contains digits (e.g. 7Up):
        if (System.Text.RegularExpressions.Regex.IsMatch(firstWord, @"\d"))
        {
            return firstWord;
        }

        // If there are multiple words and no number, use first two words (e.g. زيت-زيتون)
        if (tokens.Length > 1)
        {
            return $"{firstWord}-{tokens[1]}";
        }

        // Single word without number:
        return $"{firstWord}-1";
    }

    [RelayCommand]
    public async Task AddProductAsync()
    {
        if (string.IsNullOrWhiteSpace(NewName))
        {
            HasError = true;
            Status = "اسم الصنف مطلوب";
            return;
        }

        if (string.IsNullOrWhiteSpace(NewSku))
        {
            NewSku = GenerateSkuFromName(NewName);
        }

        if (string.IsNullOrWhiteSpace(NewSku))
        {
            NewSku = $"PRD-{DateTime.UtcNow.Ticks % 1000000:D6}";
        }

        if (string.IsNullOrWhiteSpace(NewBaseUnit))
        {
            HasError = true;
            Status = "اكتب اسم وحدة الأساس (مثل: قطعة، كرتون)";
            return;
        }

        try
        {
            using var scope = _services.CreateScope();
            var ctx = scope.ServiceProvider.GetRequiredService<DaftarContext>();

            var baseSku = Product.NormalizeSku(NewSku);
            var sku = baseSku;

            if (await ctx.Products.AnyAsync(p => p.Sku == sku))
            {
                if (!_isSkuAutoGenerated)
                {
                    HasError = true;
                    Status = $"الكود {sku} مستخدم بالفعل";
                    return;
                }

                // If auto-generated, find next unique candidate
                int counter = 2;
                while (await ctx.Products.AnyAsync(p => p.Sku == $"{baseSku}-{counter}"))
                {
                    counter++;
                }
                sku = $"{baseSku}-{counter}";
            }

            var product = new Product(sku, NewName.Trim())
            {
                ReorderLevel = decimal.TryParse(NewReorderLevel, out var reorder) ? reorder : null,
            };

            var purchasePrice = decimal.TryParse(NewPurchasePrice, out var pp) && pp >= 0m
                ? Rounding.Unit(pp)
                : 0m;

            var baseUnit = new ProductUnit
            {
                Name = NewBaseUnit.Trim(),
                Factor = 1m,
                IsBase = true,
                IsDefaultSale = true,
                IsDefaultPurchase = true,
                PurchasePrice = purchasePrice,
                Barcode = string.IsNullOrWhiteSpace(NewBarcode) ? null : NewBarcode.Trim(),
            };

            product.Units.Add(baseUnit);
            ctx.Products.Add(product);
            await ctx.SaveChangesAsync();

            baseUnit.ProductId = product.Id;
            await ctx.SaveChangesAsync();

            // If sale price was specified, record it in default price list
            if (decimal.TryParse(NewSalePrice, out var sp) && sp > 0m && _priceListId != 0)
            {
                ctx.ProductPrices.Add(new ProductPrice
                {
                    PriceListId = _priceListId,
                    ProductUnitId = baseUnit.Id,
                    Price = Rounding.Unit(sp),
                    EffectiveFrom = DateOnly.FromDateTime(DateTime.Now),
                });
                await ctx.SaveChangesAsync();
            }

            HasError = false;
            Status = $"تمت إضافة الصنف {sku} بنجاح";
            _lastAutoSku = string.Empty;
            _isSkuAutoGenerated = true;
            NewSku = string.Empty;
            NewName = string.Empty;
            NewReorderLevel = string.Empty;
            NewPurchasePrice = string.Empty;
            NewSalePrice = string.Empty;
            NewBarcode = string.Empty;
            IsAddingNewProduct = false;

            await ReloadProductsAsync(ctx);
            await SelectProductAsync(Products.FirstOrDefault(p => p.Id == product.Id));
        }
        catch (Exception ex)
        {
            HasError = true;
            Status = $"خطأ: {ex.Message}";
        }
    }

