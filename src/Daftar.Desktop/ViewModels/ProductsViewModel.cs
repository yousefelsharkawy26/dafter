    private void UpdateProfitPreview()
    {
        var hasPurchase = decimal.TryParse(UnitPurchasePrice, out var purchase) && purchase >= 0;
        var hasSale = decimal.TryParse(UnitSalePrice, out var sale) && sale >= 0;

        if (hasPurchase && hasSale && purchase > 0 && sale > 0)
        {
            var profit = sale - purchase;
            var margin = Math.Round((profit / purchase) * 100m, 1);
            UnitProfitMarginPreview = $"هامش الربح: {margin:+0.0;-0.0;0}% (الربح: {profit:N2} ج.م)";
        }
        else if (hasPurchase && purchase > 0)
        {
            UnitProfitMarginPreview = $"سعر الشراء: {purchase:N2} ج.م";
        }
        else
        {
            UnitProfitMarginPreview = string.Empty;
        }
    }

