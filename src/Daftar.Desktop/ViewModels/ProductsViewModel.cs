    [RelayCommand]
    public async Task SelectProductAsync(ProductRow? row)
    {
        if (row is null || _selectingProduct)
            return;

        _selectingProduct = true;
        try
        {
        _selectedProductId = row.Id;
        SelectedProduct = row;          // triggers OnSelectedProductChanged — guard prevents loop
        IsAddingNewProduct = false;
        CancelEditUnit();

        using var scope = _services.CreateScope();
        var ctx = scope.ServiceProvider.GetRequiredService<DaftarContext>();

        var product = await ctx.Products.FirstOrDefaultAsync(p => p.Id == row.Id);
        if (product is not null)
        {
            EditName = product.Name;
            EditSku = product.Sku;
            EditReorderLevel = product.ReorderLevel?.ToString("G29") ?? string.Empty;
            EditIsActive = product.IsActive;
        }

        CurrentOnHand = row.TotalOnHand;
        CurrentOnHandUnit = row.BaseUnitName;
        IsCurrentLowStock = row.IsLowStock;

        Units.Clear();
        foreach (var unit in await ctx.ProductUnits
                     .Where(u => u.ProductId == row.Id)
                     .OrderByDescending(u => u.IsBase)
                     .ThenBy(u => u.Factor)
                     .ToListAsync())
        {
            decimal salePrice = 0m;
            var latestSalePrice = await ctx.ProductPrices
                .Where(p => p.ProductUnitId == unit.Id)
                .OrderByDescending(p => p.EffectiveFrom)
                .Select(p => (decimal?)p.Price)
                .FirstOrDefaultAsync();
            if (latestSalePrice.HasValue)
                salePrice = latestSalePrice.Value;

            Units.Add(new UnitRow(
                Id: unit.Id,
                Name: unit.Name,
                Factor: unit.Factor,
                IsBase: unit.IsBase,
                IsDefaultSale: unit.IsDefaultSale,
                IsDefaultPurchase: unit.IsDefaultPurchase,
                Barcode: unit.Barcode,
                ProductId: row.Id,
                PurchasePrice: unit.PurchasePrice,
                SalePrice: salePrice));
        }

        Prices.Clear();
        var unitIds = Units.Select(u => u.Id).ToList();
        foreach (var price in await ctx.ProductPrices
                     .Where(p => unitIds.Contains(p.ProductUnitId))
                     .OrderByDescending(p => p.EffectiveFrom)
                     .ToListAsync())
        {
            var unit = Units.FirstOrDefault(u => u.Id == price.ProductUnitId);
            Prices.Add(new PriceRow(unit?.Name ?? "?", price.Price, price.EffectiveFrom));
        }

        PriceUnit = Units.FirstOrDefault(u => u.IsDefaultSale) ?? Units.FirstOrDefault();
        HasError = false;
        Status = $"صنف: {row.Name} ({Units.Count} وحدة · {Prices.Count} سعر)";
        }
        finally
        {
            _selectingProduct = false;
        }
    }

