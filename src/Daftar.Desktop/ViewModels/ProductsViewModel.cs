    [RelayCommand]
    public async Task DeleteUnitAsync(UnitRow? unit)
    {
        if (unit is null)
            return;

        if (unit.IsBase)
        {
            HasError = true;
            Status = "لا يمكن حذف وحدة الأساس للصنف";
            return;
        }

        try
        {
            using var scope = _services.CreateScope();
            var ctx = scope.ServiceProvider.GetRequiredService<DaftarContext>();

            // Check if unit is in any invoice lines or lot records
            var hasPrices = await ctx.ProductPrices.AnyAsync(p => p.ProductUnitId == unit.Id);
            if (hasPrices)
            {
                var prices = await ctx.ProductPrices.Where(p => p.ProductUnitId == unit.Id).ToListAsync();
                ctx.ProductPrices.RemoveRange(prices);
            }

            var dbUnit = await ctx.ProductUnits.FirstOrDefaultAsync(u => u.Id == unit.Id);
            if (dbUnit is not null)
            {
                ctx.ProductUnits.Remove(dbUnit);
                await ctx.SaveChangesAsync();
            }

            HasError = false;
            Status = $"تم حذف الوحدة '{unit.Name}'";
            await SelectProductAsync(SelectedProduct);
        }
        catch (Exception ex)
        {
            HasError = true;
            Status = $"تعذر حذف الوحدة (مرتبطة بفواتير أو دفعات سابقة): {ex.Message}";
        }
    }

    [RelayCommand]
    public async Task AddPriceAsync()
    {
        if (_selectedProductId == 0 || PriceUnit is null)
        {
            HasError = true;
            Status = "اختر صنفاً ووحدة";
            return;
        }

        if (!decimal.TryParse(PriceAmount, out var amount) || amount < 0m)
        {
            HasError = true;
            Status = "السعر يجب أن يكون رقماً صحيحاً أو عشرياً موجباً";
            return;
        }

        if (_priceListId == 0)
        {
            HasError = true;
            Status = "لا توجد قائمة أسعار افتراضية";
            return;
        }

        try
        {
            using var scope = _services.CreateScope();
            var ctx = scope.ServiceProvider.GetRequiredService<DaftarContext>();

            var today = DateOnly.FromDateTime(DateTime.Now);
            var existingToday = await ctx.ProductPrices
                .FirstOrDefaultAsync(p => p.PriceListId == _priceListId && p.ProductUnitId == PriceUnit.Id && p.EffectiveFrom == today);

            if (existingToday is not null)
            {
                existingToday.Price = Rounding.Unit(amount);
            }
            else
            {
                ctx.ProductPrices.Add(new ProductPrice
                {
                    PriceListId = _priceListId,
                    ProductUnitId = PriceUnit.Id,
                    Price = Rounding.Unit(amount),
                    EffectiveFrom = today,
                });
            }

            await ctx.SaveChangesAsync();

            HasError = false;
            Status = $"تم تسجيل السعر: {PriceUnit.Name} = {Rounding.Unit(amount):N2} ج.م";
            PriceAmount = string.Empty;

            await SelectProductAsync(SelectedProduct);
        }
        catch (Exception ex)
        {
            HasError = true;
            Status = $"خطأ: {ex.Message}";
        }
    }

    [RelayCommand]
    public async Task ToggleActiveAsync(ProductRow? row)
    {
        row ??= SelectedProduct;
        if (row is null)
            return;

        using var scope = _services.CreateScope();
        var ctx = scope.ServiceProvider.GetRequiredService<DaftarContext>();

        var product = await ctx.Products.FirstOrDefaultAsync(p => p.Id == row.Id);
        if (product is null)
            return;

        product.IsActive = !product.IsActive;
        await ctx.SaveChangesAsync();

        HasError = false;
        Status = product.IsActive ? $"تم تفعيل الصنف '{product.Name}'" : $"تم تعطيل الصنف '{product.Name}'";

        await ReloadProductsAsync(ctx);
        if (SelectedProduct?.Id == row.Id)
            await SelectProductAsync(Products.FirstOrDefault(p => p.Id == row.Id));
    }

    partial void OnSelectedProductChanged(ProductRow? value)
    {
        OnPropertyChanged(nameof(HasSelection));
        OnPropertyChanged(nameof(ShowProductDetails));
        OnPropertyChanged(nameof(ShowEmptyState));
        // Only auto-load when the change came from the ListBox binding (not from SelectProductAsync itself)
        if (value is not null && !IsAddingNewProduct && !_selectingProduct)
            _ = SelectProductAsync(value);
    }

    partial void OnIsAddingNewProductChanged(bool value)
    {
        OnPropertyChanged(nameof(ShowProductDetails));
        OnPropertyChanged(nameof(ShowEmptyState));
    }

    /// <summary>True when a product is selected AND we are NOT showing the add form.</summary>
    public bool ShowProductDetails => HasSelection && !IsAddingNewProduct;

    /// <summary>True when nothing is selected AND we are NOT showing the add form.</summary>
    public bool ShowEmptyState => !HasSelection && !IsAddingNewProduct;
