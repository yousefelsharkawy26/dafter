    [RelayCommand]
    public async Task AddUnitAsync()
    {
        if (_selectedProductId == 0)
        {
            HasError = true;
            Status = "اختر صنفاً أولاً";
            return;
        }

        if (string.IsNullOrWhiteSpace(UnitName))
        {
            HasError = true;
            Status = "اسم الوحدة مطلوب";
            return;
        }

        if (!decimal.TryParse(UnitFactor, out var factor) || factor <= 0m)
        {
            HasError = true;
            Status = "معامل التحويل يجب أن يكون أكبر من صفر";
            return;
        }

        try
        {
            using var scope = _services.CreateScope();
            var ctx = scope.ServiceProvider.GetRequiredService<DaftarContext>();

            var name = UnitName.Trim();
            if (await ctx.ProductUnits.AnyAsync(u => u.ProductId == _selectedProductId && u.Name == name))
            {
                HasError = true;
                Status = $"الوحدة '{name}' موجودة بالفعل لهذا الصنف";
                return;
            }

            var purchasePrice = decimal.TryParse(UnitPurchasePrice, out var pp) && pp >= 0m
                ? Rounding.Unit(pp)
                : 0m;

            var unit = new ProductUnit
            {
                ProductId = _selectedProductId,
                Name = name,
                Factor = factor,
                IsBase = UnitIsBase,
                IsDefaultSale = UnitDefaultSale,
                IsDefaultPurchase = UnitDefaultPurchase,
                Barcode = string.IsNullOrWhiteSpace(UnitBarcode) ? null : UnitBarcode.Trim(),
                PurchasePrice = purchasePrice,
            };

            if (unit.IsBase)
            {
                var others = await ctx.ProductUnits
                    .Where(u => u.ProductId == _selectedProductId && u.IsBase)
                    .ToListAsync();
                foreach (var other in others)
                    other.IsBase = false;
                await ctx.SaveChangesAsync();
            }

            if (unit.IsDefaultSale)
            {
                var others = await ctx.ProductUnits
                    .Where(u => u.ProductId == _selectedProductId && u.IsDefaultSale)
                    .ToListAsync();
                foreach (var other in others)
                    other.IsDefaultSale = false;
                await ctx.SaveChangesAsync();
            }

            if (unit.IsDefaultPurchase)
            {
                var others = await ctx.ProductUnits
                    .Where(u => u.ProductId == _selectedProductId && u.IsDefaultPurchase)
                    .ToListAsync();
                foreach (var other in others)
                    other.IsDefaultPurchase = false;
                await ctx.SaveChangesAsync();
            }

            ctx.ProductUnits.Add(unit);
            await ctx.SaveChangesAsync();

            if (decimal.TryParse(UnitSalePrice, out var sp) && sp > 0m && _priceListId != 0)
            {
                ctx.ProductPrices.Add(new ProductPrice
                {
                    PriceListId = _priceListId,
                    ProductUnitId = unit.Id,
                    Price = Rounding.Unit(sp),
                    EffectiveFrom = DateOnly.FromDateTime(DateTime.Now),
                });
                await ctx.SaveChangesAsync();
            }

            HasError = false;
            Status = $"تمت إضافة الوحدة '{name}' بنجاح";
            CancelEditUnit();

            await SelectProductAsync(SelectedProduct);
        }
        catch (Exception ex)
        {
            HasError = true;
            Status = $"خطأ: {ex.Message}";
        }
    }

    private async Task UpdateUnitAsync()
    {
        if (EditingUnitId == 0)
            return;

        if (string.IsNullOrWhiteSpace(UnitName))
        {
            HasError = true;
            Status = "اسم الوحدة مطلوب";
            return;
        }

        if (!decimal.TryParse(UnitFactor, out var factor) || factor <= 0m)
        {
            HasError = true;
            Status = "معامل التحويل يجب أن يكون أكبر من صفر";
            return;
        }

        try
        {
            using var scope = _services.CreateScope();
            var ctx = scope.ServiceProvider.GetRequiredService<DaftarContext>();

            var unit = await ctx.ProductUnits.FirstOrDefaultAsync(u => u.Id == EditingUnitId);
            if (unit is null)
            {
                HasError = true;
                Status = "الوحدة غير موجودة";
                return;
            }

            var name = UnitName.Trim();
            if (name != unit.Name && await ctx.ProductUnits.AnyAsync(u => u.ProductId == unit.ProductId && u.Name == name && u.Id != unit.Id))
            {
                HasError = true;
                Status = $"اسم الوحدة '{name}' مستخدم بالفعل لهذا الصنف";
                return;
            }

            unit.Name = name;
            unit.Factor = factor;
            unit.Barcode = string.IsNullOrWhiteSpace(UnitBarcode) ? null : UnitBarcode.Trim();
            unit.PurchasePrice = decimal.TryParse(UnitPurchasePrice, out var pp) && pp >= 0m ? Rounding.Unit(pp) : 0m;

            if (UnitIsBase && !unit.IsBase)
            {
                var others = await ctx.ProductUnits
                    .Where(u => u.ProductId == unit.ProductId && u.IsBase && u.Id != unit.Id)
                    .ToListAsync();
                foreach (var other in others)
                    other.IsBase = false;
                await ctx.SaveChangesAsync();
                unit.IsBase = true;
                unit.Factor = 1m;
            }

            if (UnitDefaultSale)
            {
                var others = await ctx.ProductUnits
                    .Where(u => u.ProductId == unit.ProductId && u.IsDefaultSale && u.Id != unit.Id)
                    .ToListAsync();
                foreach (var other in others)
                    other.IsDefaultSale = false;
                unit.IsDefaultSale = true;
            }
            else
            {
                unit.IsDefaultSale = false;
            }

            if (UnitDefaultPurchase)
            {
                var others = await ctx.ProductUnits
                    .Where(u => u.ProductId == unit.ProductId && u.IsDefaultPurchase && u.Id != unit.Id)
                    .ToListAsync();
                foreach (var other in others)
                    other.IsDefaultPurchase = false;
                unit.IsDefaultPurchase = true;
            }
            else
            {
                unit.IsDefaultPurchase = false;
            }

            await ctx.SaveChangesAsync();

            // Record sale price if updated
            if (decimal.TryParse(UnitSalePrice, out var sp) && sp > 0m && _priceListId != 0)
            {
                var today = DateOnly.FromDateTime(DateTime.Now);
                var todayPrice = await ctx.ProductPrices
                    .FirstOrDefaultAsync(p => p.PriceListId == _priceListId && p.ProductUnitId == unit.Id && p.EffectiveFrom == today);

                if (todayPrice is not null)
                {
                    todayPrice.Price = Rounding.Unit(sp);
                    await ctx.SaveChangesAsync();
                }
                else
                {
                    ctx.ProductPrices.Add(new ProductPrice
                    {
                        PriceListId = _priceListId,
                        ProductUnitId = unit.Id,
                        Price = Rounding.Unit(sp),
                        EffectiveFrom = today,
                    });
                    await ctx.SaveChangesAsync();
                }
            }

            HasError = false;
            Status = $"تم تحديث الوحدة '{unit.Name}' بنجاح";
            CancelEditUnit();

            await SelectProductAsync(SelectedProduct);
        }
        catch (Exception ex)
        {
            HasError = true;
            Status = $"خطأ: {ex.Message}";
        }
    }

