    public async Task SaveProductEditAsync()
    {
        if (_selectedProductId == 0)
            return;

        if (string.IsNullOrWhiteSpace(EditSku) || string.IsNullOrWhiteSpace(EditName))
        {
            HasError = true;
            Status = "الكود والاسم مطلوبان";
            return;
        }

        try
